import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { loadChromium, edgeLaunchOptions } from './browser-runtime.mjs';
import { mkdir } from 'node:fs/promises';
const chromium = await loadChromium();
const root = resolve(process.env.QIBIAN_EXTENSION_ROOT || '.');
const context = await chromium.launchPersistentContext('', { ...edgeLaunchOptions(), headless:true, args:[`--disable-extensions-except=${root}`, `--load-extension=${root}`] });
const errors = [], passed = [];
let png;
try {
  const scratch = context.pages()[0] || await context.newPage();
  png = Buffer.from((await scratch.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = canvas.height = 8; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#287474'; ctx.fillRect(0, 0, 8, 8); return canvas.toDataURL('image/png'); })).split(',')[1], 'base64');
  await context.route(/^https?:\/\//, async route => {
    const url = new URL(route.request().url());
    if (url.pathname.startsWith('/icon')) return route.fulfill({ contentType:'image/png', body:png });
    if (url.pathname === '/unavailable' || url.pathname === '/favicon.ico') return route.fulfill({ status:404, body:'missing' });
    if (url.pathname === '/slow') await new Promise(resolve => setTimeout(resolve, 1300));
    return route.fulfill({ contentType:'text/html; charset=utf-8', body:`<!doctype html><meta charset="utf-8"><title>${url.pathname === '/current' ? '当前网页标题' : '自动识别的标题'}</title><link rel="icon" href="/icon.png"><h1>网页</h1>` });
  });
  const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  const page = await context.newPage(); page.setDefaultTimeout(12000); page.on('pageerror', error => errors.push(error.message));
  await page.goto('https://fixture.test/current?keep=1#section');
  await page.locator('#qibian-mini-rail').getByRole('button', { name:'展开栖边', exact:true }).click();
  const panel = page.frameLocator('#qibian-mini-rail iframe.workspace-frame');
  const add = () => panel.getByRole('button', { name:/添加内容/ }).click();
  const save = async () => { await panel.locator('#submit-card').click(); try { await panel.locator('#editor').waitFor({ state:'hidden' }); } catch (e) { console.log('FORM ERROR', await panel.locator('#form-error').textContent()); throw e; } };
  const stored = () => worker.evaluate(async () => (await chrome.storage.local.get('workspace')).workspace);
  await add();
  await panel.locator('.website-read-status').getByText('已读取网站图标，保存后可离线显示。', { exact:true }).waitFor();
  assert.equal(await panel.getByLabel('网站地址', { exact:true }).inputValue(), 'https://fixture.test/current?keep=1#section');
  assert.equal(await panel.getByLabel('卡片名称', { exact:true }).inputValue(), '当前网页标题');
  await save();
  let card = (await stored()).cards.find(c => c.url?.includes('/current'));
  assert.match(card.icon, /^data:image\/png;base64,/);
  const automaticId = card.id;
  assert.equal(card.autoIcon, true);
  passed.push('embedded sidebar reads the actual webpage URL, query/hash, title and favicon');
  await add();
  await panel.getByLabel('网站地址', { exact:true }).fill('https://fixture.test/manual');
  await panel.locator('.website-read-status').getByText('已读取网站图标，保存后可离线显示。', { exact:true }).waitFor();
  assert.equal(await panel.getByLabel('卡片名称', { exact:true }).inputValue(), '自动识别的标题');
  await panel.getByLabel('或上传图标图片', { exact:true }).setInputFiles({ name:'custom.png', mimeType:'image/png', buffer:png });
  await save(); card = (await stored()).cards.find(c => c.url?.includes('/manual'));
  assert.equal(card.icon, 'data:image/png;base64,' + png.toString('base64'));
  passed.push('pasted URLs fetch title/favicon; uploaded icon takes precedence');
  await add();
  await panel.getByLabel('网站地址', { exact:true }).fill('https://fixture.test/slow');
  await new Promise(resolve => setTimeout(resolve, 650));
  await panel.getByLabel('网站地址', { exact:true }).fill('https://fixture.test/unavailable');
  await panel.getByLabel('卡片名称', { exact:true }).fill('我的名称');
  await panel.getByLabel('网站图标（文字或表情）', { exact:true }).fill('🌲');
  await panel.locator('.website-read-status').getByText(/未能读取网站图标/).waitFor();
  await save(); card = (await stored()).cards.find(c => c.url?.includes('/unavailable'));
  assert.equal(card.title, '我的名称'); assert.equal(card.icon, '🌲');
  passed.push('stale responses cannot overwrite edits; unavailable sites can still be saved');
  const uploadedCard = panel.locator('.card').filter({ has:panel.getByRole('heading', { name:'自动识别的标题', exact:true }) });
  await uploadedCard.getByRole('button', { name:'编辑 自动识别的标题', exact:true }).click();
  await panel.getByLabel('网站地址', { exact:true }).fill('https://fixture.test/manual-updated');
  await save(); assert.equal((await stored()).cards.find(c => c.url?.includes('/manual')).icon, 'data:image/png;base64,' + png.toString('base64'));
  assert.equal((await stored()).cards.find(c => c.url?.includes('/manual')).autoIcon, false);
  await uploadedCard.getByRole('button', { name:'编辑 自动识别的标题', exact:true }).click();
  await panel.getByRole('button', { name:'自动读取图标', exact:true }).click();
  await panel.locator('.website-read-status').getByText('已读取网站图标，保存后可离线显示。', { exact:true }).waitFor();
  await save(); assert.notEqual((await stored()).cards.find(c => c.url?.includes('/manual')).icon, 'data:image/png;base64,' + png.toString('base64'));
  passed.push('editing preserves custom icons; explicit automatic refresh replaces them');
  await panel.locator(`.card[data-id="${automaticId}"]`).getByRole('button', { name:'编辑 当前网页标题', exact:true }).click();
  await panel.getByLabel('网站地址', { exact:true }).fill('https://fixture.test/unavailable?automatic=1');
  await panel.locator('.website-read-status').getByText(/未能读取网站图标/).waitFor();
  await save();
  assert.equal((await stored()).cards.find(c => c.id === automaticId).icon, '');
  assert.equal((await stored()).cards.find(c => c.id === automaticId).autoIcon, false);
  passed.push('changing an automatic-icon website never retains the previous website icon');
  await add(); await panel.locator('.website-read-status').getByText('已读取网站图标，保存后可离线显示。', { exact:true }).waitFor();
  await mkdir('artifacts', { recursive:true }); await page.screenshot({ path:resolve('artifacts/website-auto-1.5.1.png') });
  assert.deepEqual(errors, []); console.log(JSON.stringify({ passed, errors }, null, 2));
} finally { await context.close(); }
