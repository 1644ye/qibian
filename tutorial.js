export function mountTutorial(settings) {
  if (settings.querySelector('#usage-guide')) return;
  const guide = document.createElement('details'); guide.id = 'usage-guide';
  const summary = document.createElement('summary'); summary.textContent = '使用教程 · 导入网站与管理歌单'; guide.append(summary);
  const hint = document.createElement('p'); hint.className = 'muted'; hint.textContent = '点击主题查看步骤；教程保存在插件内，离线也能查看。'; guide.append(hint);
  for (const [title, steps, note] of topics) {
    const topic = document.createElement('details'); topic.className = 'guide-topic';
    const heading = document.createElement('summary'); heading.textContent = title; topic.append(heading);
    const list = document.createElement('ol');
    for (const text of steps) { const item = document.createElement('li'); item.textContent = text; list.append(item); }
    const tip = document.createElement('p'); tip.className = 'muted'; tip.textContent = note;
    topic.append(list, tip); guide.append(topic);
  }
  settings.querySelector('.dialog-heading').after(guide);
}
